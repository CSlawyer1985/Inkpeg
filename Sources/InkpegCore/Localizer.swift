public struct Localizer {
    private let preferred: Bundle
    private let english: Bundle
    public init(localeIdentifier: String = Locale.preferredLanguages.first ?? "en", bundle: Bundle? = nil) {
        let resources = bundle ?? ResourceBundleLocator.bundledResources
        let language = localeIdentifier.lowercased().replacingOccurrences(of: "_", with: "-")
        let code = language.hasPrefix("zh") ? "zh-Hans" : language.hasPrefix("es") ? "es" : "en"
        english = Self.localeBundle("en", in: resources) ?? resources
        preferred = Self.localeBundle(code, in: resources) ?? english
    }
    public func string(_ key: MessageKey) -> String {
        let fallback = english.localizedString(forKey: key.rawValue, value: key.rawValue, table: nil)
        return preferred.localizedString(forKey: key.rawValue, value: fallback, table: nil)
    }
    private static func localeBundle(_ code: String, in resources: Bundle) -> Bundle? {
        resources.url(forResource: code, withExtension: "lproj").flatMap(Bundle.init(url:))
    }
}
